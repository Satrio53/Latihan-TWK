// FUNGSI PARSER DENGAN PENANGANAN BARIS MULTIPLE
function parseTxtToJSON(text) {
    let listSoal = [];
    const normalizedText = text.replace(/\r\n/g, '\n');

    // Pecah blok berdasarkan awal baris yang berisi angka (misal "251.", "252.")
    const blokSoal = normalizedText.split(/(?=^\d+[\.\)])/m).filter(b => b.trim().length > 0);

    blokSoal.forEach(blok => {
        const baris = blok.split('\n').map(b => b.trim()).filter(b => b.length > 0);
        if (baris.length === 0) return;

        let bagianTeksSoal = [];
        let pilihan = [];
        let jawabanIdx = 0;
        let pembahasan = "";

        for (let i = 0; i < baris.length; i++) {
            const line = baris[i];

            // Cek Opsi Pilihan A - E
            if (/^[A-E][\.\)]/i.test(line)) {
                pilihan.push(line);
            } 
            // Cek Kunci Jawaban
            else if (/^(kunci|jawaban|ans):/i.test(line)) {
                const charKunci = line.split(':')[1].trim().toUpperCase();
                const mapKunci = { 'A': 0, 'B': 1, 'C': 2, 'D': 3, 'E': 4 };
                if (mapKunci[charKunci] !== undefined) {
                    jawabanIdx = mapKunci[charKunci];
                }
            } 
            // Cek Pembahasan
            else if (/^pembahasan:/i.test(line)) {
                pembahasan = line.replace(/^pembahasan:\s*/i, '');
            } 
            // Jika bukan opsi/kunci/pembahasan, berarti ini TEKS SOAL (meski terpisah beberapa baris)
            else {
                // Hapus angka nomor lama di baris pertama saja
                let cleanLine = line.replace(/^\d+[\.\)]\s*/, '');
                if (cleanLine.length > 0) {
                    bagianTeksSoal.push(cleanLine);
                }
            }
        }

        // Gabungkan baris-baris teks soal menjadi 1 kalimat utuh
        let teksSoalLengkap = bagianTeksSoal.join(' ');

        if (pilihan.length > 0 && teksSoalLengkap.length > 0) {
            listSoal.push({
                soal: teksSoalLengkap,
                pilihan: pilihan,
                jawaban: jawabanIdx,
                pembahasan: pembahasan || "Belum ada pembahasan."
            });
        }
    });

    return listSoal;
}
// 2. Fungsi Parser Teks
function parseTxtToJSON(text) {
    let listSoal = [];
    const normalizedText = text.replace(/\r\n/g, '\n');

    // 1. PETAKAN SEMUA KUNCI JAWABAN DULU (Mencari pola "1 A", "2 B", "251 B", dst di bagian bawah)
    let mapKunci = {};
    const mapHuruf = { 'A': 0, 'B': 1, 'C': 2, 'D': 3, 'E': 4 };
    
    // Regex mencari baris yang berisi angka + huruf kunci (contoh: "1 A", "251 B", "1. A")
    const regexKunci = /^\s*(\d+)[\.\)]?\s+([A-E])\s*$/gim;
    let matchKunci;
    while ((matchKunci = regexKunci.exec(normalizedText)) !== null) {
        const noSoal = matchKunci[1];
        const hurufKunci = matchKunci[2].toUpperCase();
        mapKunci[noSoal] = mapHuruf[hurufKunci];
    }

    // 2. PECAH BLOK SOAL BERDASARKAN NOMOR
    const blokSoal = normalizedText.split(/(?=^\s*\d+[\.\)])/m).filter(b => b.trim().length > 0);

    blokSoal.forEach(blok => {
        const baris = blok.split('\n').map(b => b.trim()).filter(b => b.length > 0);
        if (baris.length === 0) return;

        // Ambil nomor soal asli dari baris pertama (misal "251" dari "251.")
        const matchNomor = baris[0].match(/^\s*(\d+)[\.\)]?/);
        if (!matchNomor) return; // Jika bukan blok soal (misal blok kunci di bawah), lewati

        const nomorSoalAsli = matchNomor[1];

        let bagianTeksSoal = [];
        let pilihan = [];
        let pembahasan = "";

        baris.forEach(line => {
            // Cek Pilihan Jawaban A - E
            if (/^[A-E][\.\)]/i.test(line)) {
                pilihan.push(line);
            } 
            // Cek Pembahasan (jika ada)
            else if (/^pembahasan\s*[:\-]?/i.test(line)) {
                pembahasan = line.replace(/^pembahasan\s*[:\-]?\s*/i, '');
            } 
            // Jika bukan pilihan/pembahasan dan bukan baris kunci jawaban murni
            else if (!/^\s*\d+[\.\)]?\s+[A-E]\s*$/i.test(line)) {
                let cleanLine = line.replace(/^\d+[\.\)]?\s*/, '').trim();
                if (cleanLine.length > 0) {
                    bagianTeksSoal.push(cleanLine);
                }
            }
        });

        let teksSoalLengkap = bagianTeksSoal.join(' ');

        // Ambil kunci jawaban berdasarkan nomor soal aslinya dari mapKunci
        // Jika tidak ketemu di map, default ke 0 (A)
        let jawabanIdx = mapKunci[nomorSoalAsli] !== undefined ? mapKunci[nomorSoalAsli] : 0;

        if (pilihan.length > 0 && teksSoalLengkap.length > 0) {
            listSoal.push({
                soal: teksSoalLengkap,
                pilihan: pilihan,
                jawaban: jawabanIdx,
                pembahasan: pembahasan || "Belum ada pembahasan."
            });
        }
    });

    return listSoal;
}

